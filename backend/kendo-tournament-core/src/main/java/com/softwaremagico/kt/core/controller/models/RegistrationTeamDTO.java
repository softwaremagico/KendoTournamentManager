import java.io.Serial;
import java.io.Serializable;

/** Public projection of a team: only its name and remaining capacity. */
@SuppressWarnings("java:S2160")
public class RegistrationTeamDTO implements Serializable {

    @Serial
    private static final long serialVersionUID = -5768570093880382412L;

    private String name;

    private Integer freeSlots;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Integer getFreeSlots() {
        return freeSlots;
    }

    public void setFreeSlots(Integer freeSlots) {
        this.freeSlots = freeSlots;
    }
}
